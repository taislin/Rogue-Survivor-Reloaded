function newParams(): Parameters {
  const params = new Parameters();
  params.district = new District(new Point(0, 0), DistrictKind.SHOPPING);
  params.mapWidth = params.mapHeight = DISTRICT_SIZE;
  params.generateShoppingMall = true;
  return params;
}

/**
 * Generate a real mall district and hand back the two levels, by name.
 *
 * `District.entryMap` is installed *after* generation, exactly as
 * `GenerateDistrictEntryMap` does at `RogueGame.cs:5008-5014`, so the two linked maps
 * are the first two entries of `district.maps` and the surface map is the third.
 */
function generateLevels(seed = SEED): { upper: GameMap; parking: GameMap; ground: GameMap; district: District } {
  const district = new District(new Point(0, 0), DistrictKind.SHOPPING);
  const params = newParams();
  params.district = district;
  const ground = new BaseTownGenerator({ rules, ApplyOnFire: () => undefined } as never, params).generate(seed);
  district.entryMap = ground;

  const upper = district.maps.find((m) => m.name === "Shopping Mall - Upper Level");
  const parking = district.maps.find((m) => m.name === "Shopping Mall - Parking");
  if (!upper || !parking) throw new Error("the mall did not link its two levels");
  return { upper, parking, ground, district };
}

function modelAt(map: GameMap, x: number, y: number) {
  return map.getTileAt(x, y)!.model;
}

function objAt(map: GameMap, x: number, y: number) {
  return map.getMapObjectAt(x, y);
}

/** Every tile whose map object satisfies `keep`, as `[x, y]`. */
function objectsWhere(map: GameMap, keep: (name: string, imageId: string) => boolean): [number, number][] {
  const out: [number, number][] = [];
  for (let x = 0; x < map.width; x++) {
    for (let y = 0; y < map.height; y++) {
      const obj = objAt(map, x, y);
      if (obj && keep(obj.name, obj.imageId)) out.push([x, y]);
    }
  }
  return out;
}

/** Two hashes over tile models, objects, decorations, `isInside` and ground stacks. */
function fingerprint(map: GameMap): string {
  let h1 = 0x811c9dc5;
  let h2 = 0x01000193;
  for (let x = 0; x < map.width; x++) {
    for (let y = 0; y < map.height; y++) {
      const tile = map.getTileAt(x, y)!;
      const obj = objAt(map, x, y);
      const stack = map.getItemsAt(new Point(x, y));
      const cell = `${tile.model.id}|${obj ? obj.imageId : "-"}|${(tile.getDecorations ?? []).join(",")}|${
        tile.isInside ? 1 : 0
      }|${stack ? stack.countItems : 0}`;
      for (let i = 0; i < cell.length; i++) {
        h1 = Math.imul(h1 ^ cell.charCodeAt(i), 16777619) >>> 0;
        h2 = (Math.imul(h2 + cell.charCodeAt(i) + i, 2654435761) ^ (h2 >>> 7)) >>> 0;
      }
    }
  }
  return h1.toString(16).padStart(8, "0") + h2.toString(16).padStart(8, "0");
}

