/**
 * The mall's two linked levels: the food court / supermarket / two cinemas upstairs,
 * and the car park below.
 *
 * `tests/shopping-mall-building.test.ts` covers the ground floor, the district's block
 * layout and the six stair pairs, and asserts of the two levels only that they are
 * 51x51 and that the far ends of the exits exist. Everything that is *on* them is
 * here, and the shape of the file is the same as that one's: the **real**
 * `BaseTownGenerator.generate()` is driven with `Parameters.generateShoppingMall` on,
 * because a level generated by calling `generateShoppingMallUpperLevel` directly would
 * be a level with no exits on it and would not catch a stairway landing in a wall.
 *
 * What is asserted, and why these and not something tidier:
 *
 * 1. **The upper level's four regions by name and bounds.** `food court` over
 *    `(1, 1, 25, 22)` and `Supermarket` over `(26, 1, 25, 22)` are the C#'s two
 *    `MakeUniqueZone` calls (`:10205`, `:10302`); the bathrooms and the cinema foyer get
 *    **no zone at all**, which is the reference's own asymmetry and is what the
 *    corridor, the auditoria and the cubicles having no name means.
 * 2. **The pool is real water, and `hasWaterTiles` is true.** The flag's only reason in
 *    the C# (`:10189`) is the pool at `:10277-10278`, so the two are asserted together:
 *    a port that set the flag without the tiles would pass either assertion alone.
 * 3. **The parking bays are `PARKING_ASPHALT_NS` on the two edge rows and
 *    `PARKING_ASPHALT_EW` everywhere else**, which is the C#'s orientation and the one
 *    thing about this method a reader cannot guess: the two models are not
 *    interchangeable and the abandoned-car test at `:10599` accepts both.
 * 4. **The pillars and railings alternate on a five-step cycle**, and the pillar is a
 *    *tile* while the railing is a *map object* — five pillars and sixteen railings per
 *    column, sixteen columns.
 * 5. **The two power rooms are empty.** `CountAdjWalls >= 3` is unreachable in either
 *    of them, so the generator places no `power generator` at all while still creating
 *    the two `power room` zones. Asserted because it reads like a bug and *is* the
 *    C#'s arithmetic; a port that "fixed" it would fail here.
 * 6. **The stair columns still land on floor**, now that both levels have furniture: the
 *    ground floor's six exits have to arrive somewhere that is neither a wall nor a
 *    shelf, and the exits are added *after* generation, so this is the only place that
 *    can catch a level filling its own doorway.
 */

const SEED = 1;

/** `DEFAULT_DISTRICT_SIZE` — the same default the ground-floor file generates at. */
const DISTRICT_SIZE = 50;

const rules = new Rules(new DiceRoller(20250929));
